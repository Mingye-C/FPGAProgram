 function [23:0] band_color;input [4:0] n;begin
  case(n)
   0:band_color=24'h24DDEB;1:band_color=24'h28D7EE;2:band_color=24'h2BCDF0;3:band_color=24'h30CBF2;
   4:band_color=24'h35C5F4;5:band_color=24'h3BBDF6;6:band_color=24'h40B7F8;7:band_color=24'h46B0F9;
   8:band_color=24'h4CA8FB;9:band_color=24'h52A1FC;10:band_color=24'h5999FD;11:band_color=24'h608FFE;
   12:band_color=24'h6889FE;13:band_color=24'h707FFC;14:band_color=24'h7977FC;15:band_color=24'h816FFB;
   16:band_color=24'h8967F9;17:band_color=24'h925EF6;18:band_color=24'h9B56F3;19:band_color=24'hA34FEF;
   20:band_color=24'hAC48E9;21:band_color=24'hB542E4;22:band_color=24'hBB3EDF;default:band_color=24'hC13BDB;
  endcase
 end endfunction

  if(rst) begin
   de_q<=0;vs_q<=1;x_count<=0;y_count<=0;column<=0;pitch_x<=0;
   rgb1<=0;color1<=0;hit1<=0;title1<=0;col1<=0;
   de1<=0;hs1<=0;vs1<=0;out_rgb<=0;out_de<=0;out_hs<=0;out_vs<=0;
  end else begin
   de_q<=in_de;vs_q<=in_vs;
   if(frame_start) begin x_count<=0;y_count<=0;end
   else if(in_de) x_count<=px+1'b1;
   else if(de_q) begin x_count<=0;y_count<=y_count+1'b1;end
   if(frame_start || !in_de) begin column<=0;pitch_x<=0;end
   else if(bars_x) begin
    if(pitch_x==PITCH-1) begin pitch_x<=0;column<=column+1'b1;end
    else pitch_x<=pitch_x+1'b1;
   end
   rgb1<=in_rgb;color1<=band_color(column);hit1<=hit;
   title1<=fft_title_hit || level_title_hit;col1<=title_x[2:0];
   de1<=in_de;hs1<=in_hs;vs1<=in_vs;
   if(!NATIVE_TEXT && title1 && glyph[7-col1]) out_rgb<=TITLE_COLOR;
   else out_rgb<=hit1?color1:rgb1;
   out_de<=de1;out_hs<=hs1;out_vs<=vs1;
  end
 end
endmodule


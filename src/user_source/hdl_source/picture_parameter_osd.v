module external_button_level #(parameter integer DEBOUNCE_CYCLES=500000)(
 input clk,input rst,input button_n,output wire pressed);
localparam integer CW=(DEBOUNCE_CYCLES<2)?1:$clog2(DEBOUNCE_CYCLES);
(* ASYNC_REG="TRUE" *) reg [1:0] button_sync;
reg stable_n;
reg [CW-1:0] count;
assign pressed=~stable_n;
always @(posedge clk or posedge rst)begin
 if(rst)begin button_sync<=2'b11;stable_n<=1'b1;count<=0;end
 else begin
  button_sync<={button_sync[0],button_n};
  if(button_sync[1]==stable_n)count<=0;
  else if(count==DEBOUNCE_CYCLES-1)begin stable_n<=button_sync[1];count<=0;end
  else count<=count+1'b1;
 end
end
endmodule
